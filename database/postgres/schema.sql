CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_lengkap VARCHAR(120) NOT NULL,
  email VARCHAR(120) NOT NULL UNIQUE,
  username VARCHAR(60) UNIQUE,
  nip VARCHAR(60) UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  nomor_hp VARCHAR(30),
  alamat TEXT,
  jenis_anggota VARCHAR(60),
  membership_type VARCHAR(20),
  role VARCHAR(20) NOT NULL DEFAULT 'member',
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  member_code VARCHAR(20) UNIQUE,
  auth_token VARCHAR(64) UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT users_membership_type_check CHECK (membership_type IS NULL OR membership_type IN ('Umum', 'Pelajar', 'Premium')),
  CONSTRAINT users_role_check CHECK (role IN ('member', 'admin', 'staff', 'petugasRak')),
  CONSTRAINT users_status_check CHECK (status IN ('active', 'pending', 'inactive', 'blocked'))
);

CREATE TABLE IF NOT EXISTS categories (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  color VARCHAR(100),
  icon VARCHAR(50),
  description TEXT
);

CREATE TABLE IF NOT EXISTS shelves (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode VARCHAR(20) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  location VARCHAR(150),
  floor SMALLINT,
  capacity INTEGER NOT NULL DEFAULT 0 CHECK (capacity >= 0)
);

CREATE TABLE IF NOT EXISTS shelf_categories (
  shelf_id INTEGER NOT NULL REFERENCES shelves(id) ON DELETE CASCADE,
  category_id INTEGER NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
  PRIMARY KEY (shelf_id, category_id)
);

CREATE TABLE IF NOT EXISTS books (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  author VARCHAR(160) NOT NULL,
  category_id INTEGER REFERENCES categories(id) ON DELETE SET NULL,
  shelf_id INTEGER REFERENCES shelves(id) ON DELETE SET NULL,
  shelf_position VARCHAR(50),
  cover TEXT,
  rating NUMERIC(3, 1) NOT NULL DEFAULT 0 CHECK (rating >= 0 AND rating <= 5),
  published_year SMALLINT,
  pages INTEGER CHECK (pages IS NULL OR pages >= 0),
  isbn VARCHAR(40),
  stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  description TEXT,
  publisher VARCHAR(150),
  recommended BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS loan_rules (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type VARCHAR(100) NOT NULL UNIQUE,
  duration_days SMALLINT NOT NULL,
  max_renewals SMALLINT NOT NULL DEFAULT 0,
  fine_per_day NUMERIC(12, 2) NOT NULL DEFAULT 0,
  description TEXT,
  eligibility VARCHAR(150)
);

CREATE TABLE IF NOT EXISTS loans (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  book_id INTEGER NOT NULL REFERENCES books(id) ON DELETE CASCADE,
  borrowed_at TIMESTAMPTZ NOT NULL,
  due_at TIMESTAMPTZ NOT NULL,
  returned_at TIMESTAMPTZ,
  duration INTEGER NOT NULL DEFAULT 7 CHECK (duration >= 0),
  fine NUMERIC(12, 2) NOT NULL DEFAULT 0,
  is_favorite BOOLEAN NOT NULL DEFAULT FALSE,
  payment_status VARCHAR(20) NOT NULL DEFAULT 'unpaid',
  status VARCHAR(20) NOT NULL DEFAULT 'Menunggu',
  CONSTRAINT loans_payment_status_check CHECK (payment_status IN ('unpaid', 'paid')),
  CONSTRAINT loans_status_check CHECK (status IN ('Menunggu', 'Dipinjam', 'Dikembalikan', 'Selesai', 'Ditolak'))
);

CREATE TABLE IF NOT EXISTS ratings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_id INTEGER NOT NULL UNIQUE REFERENCES loans(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  rating SMALLINT NOT NULL CHECK (rating >= 1 AND rating <= 5),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS library_settings (
  id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  durasi_umum INTEGER NOT NULL DEFAULT 7,
  durasi_pelajar INTEGER NOT NULL DEFAULT 14,
  durasi_dosen INTEGER NOT NULL DEFAULT 90,
  denda_umum INTEGER NOT NULL DEFAULT 4000,
  denda_pelajar INTEGER NOT NULL DEFAULT 1000,
  denda_dosen INTEGER NOT NULL DEFAULT 0,
  denda_buku_favorit INTEGER NOT NULL DEFAULT 2000,
  batas_buku_umum INTEGER NOT NULL DEFAULT 2,
  batas_buku_pelajar INTEGER NOT NULL DEFAULT 3,
  batas_buku_dosen INTEGER NOT NULL DEFAULT 5
);

CREATE TABLE IF NOT EXISTS activity_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  admin_name VARCHAR(120) NOT NULL,
  admin_email VARCHAR(120) NOT NULL,
  module VARCHAR(30) NOT NULL,
  action VARCHAR(30) NOT NULL,
  description TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_books_category_id ON books(category_id);
CREATE INDEX IF NOT EXISTS idx_books_shelf_id ON books(shelf_id);
CREATE INDEX IF NOT EXISTS idx_books_isbn ON books(isbn);
CREATE INDEX IF NOT EXISTS idx_loans_user_id ON loans(user_id);
CREATE INDEX IF NOT EXISTS idx_loans_book_id ON loans(book_id);
CREATE INDEX IF NOT EXISTS idx_loans_status ON loans(status);
CREATE INDEX IF NOT EXISTS idx_ratings_user_id ON ratings(user_id);
CREATE INDEX IF NOT EXISTS idx_activity_logs_created_at ON activity_logs(created_at DESC);
